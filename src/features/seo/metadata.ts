import type { Metadata } from "next";

import { mediaPublicUrl } from "@/features/media/url";
import { postPath } from "@/features/posts/archives";
import { openGraphLocale } from "@/features/posts/language";
import { pagePath } from "@/features/posts/pagination";
import type { PostSummary } from "@/features/posts/types";
import type { SiteSettings } from "@/features/site-settings/model";
import { getConfiguredSiteUrl } from "@/lib/site-url";
import { feedAlternateTypes, type FeedChannel } from "./feed";

// Pure metadata builders. Paths stay relative; the root layout's metadataBase
// (NEXT_PUBLIC_SITE_URL) turns canonical and Open Graph URLs into absolute
// ones. The canonical post URL never depends on the category or tag path a
// reader arrived from.

// Unknown, unpublished, and empty-archive URLs answer 404 and stay out of
// search indexes.
export const noIndexMetadata: Metadata = {
  robots: { index: false, follow: false },
};

// Canonical URL plus the feed discovery links. Metadata merges segments
// shallowly, so a page that sets alternates replaces the root layout's and
// must repeat the site feed link, or the link disappears from that page.
// Archives add their own feed in front of it.
export function canonicalAlternates(
  path: string,
  siteName: string,
  archiveFeed?: Pick<FeedChannel, "path" | "title">,
): Metadata["alternates"] {
  const types = feedAlternateTypes(getConfiguredSiteUrl(), siteName, archiveFeed);
  return { canonical: path, ...(types ? { types } : {}) };
}

// Absolute delivery URL of a post's cover. It lives on the media origin
// (Supabase Storage, D4), not the site origin, so metadataBase does not apply.
export function postCoverImageUrl(post: Pick<PostSummary, "cover">): string | null {
  return post.cover ? mediaPublicUrl(post.cover.mediaId) : null;
}

// What the metadata builders need from the site settings (Phase 27).
export type SiteBrand = Pick<SiteSettings, "siteName" | "ogImageMediaId" | "revision">;

// The site-wide social image: the default Open Graph image chosen in the site
// settings (an absolute URL on the media origin, D4), or else the image
// generated by src/app/opengraph-image.tsx from the site name, tagline, and
// accent color. The generated route sits outside the [locale] root layout,
// so pages declare it explicitly; its URL is relative like the other
// metadata URLs and needs metadataBase, so without a configured site origin
// no generated image is declared. The ?v= revision gives the image a new URL
// after every settings save, because social platforms cache images by URL.
// The chosen image's dimensions are omitted: readers cannot read media rows.
export const defaultSocialImagePath = "/opengraph-image";
export const socialImageSize = { width: 1200, height: 630 } as const;

export type SocialImage = {
  url: string;
  alt?: string;
  width?: number;
  height?: number;
  type?: string;
};

export function defaultSocialImage(
  site: SiteBrand,
  siteUrl: URL | null = getConfiguredSiteUrl(),
): SocialImage | null {
  const chosen = site.ogImageMediaId ? mediaPublicUrl(site.ogImageMediaId) : null;
  if (chosen) return { url: chosen, alt: site.siteName };

  return siteUrl
    ? {
        url: `${defaultSocialImagePath}?v=${site.revision}`,
        alt: site.siteName,
        ...socialImageSize,
        type: "image/png",
      }
    : null;
}

// Open Graph images plus the Twitter card that matches them: a large image
// card when there is an image, a text-only summary otherwise.
export function socialImages(image: SocialImage | null, twitter: { title: string; description?: string }) {
  return {
    openGraph: image ? { images: [image] } : {},
    twitter: image
      ? { card: "summary_large_image" as const, ...twitter, images: [image] }
      : { card: "summary" as const, ...twitter },
  };
}

export function buildPostMetadata(post: PostSummary, site: SiteBrand): Metadata {
  const { siteName } = site;
  const path = postPath(post.slug);
  const description = post.excerpt ?? undefined;
  const coverUrl = postCoverImageUrl(post);
  // A post without a cover shares the site-wide image.
  const image: SocialImage | null = coverUrl
    ? { url: coverUrl, alt: post.cover?.alt || undefined }
    : defaultSocialImage(site);
  const social = socialImages(image, { title: post.title, description });

  return {
    title: post.title,
    description,
    alternates: canonicalAlternates(path, siteName),
    openGraph: {
      type: "article",
      url: path,
      siteName,
      // Omitted when no territory is known for the language.
      locale: openGraphLocale(post.language) ?? undefined,
      title: post.title,
      description,
      publishedTime: post.publishedAt,
      modifiedTime: post.updatedAt,
      authors: post.authors.map(({ author }) => author.name),
      section: post.category.name,
      tags: post.tags.map((tag) => tag.name),
      ...social.openGraph,
    },
    twitter: social.twitter,
  };
}

// Formats a later page's title ("<title> — Page 3") in the interface
// language. Callers pass the translated format (listing-metadata.ts), so this
// module stays free of copy and of the i18n runtime.
export type PageTitleFormatter = (title: string, page: number) => string;

// Later pages of a listing carry the page number in their title.
export function pageTitle(title: string, page: number, format: PageTitleFormatter) {
  return page > 1 ? format(title, page) : title;
}

// Each page of a listing is its own canonical URL (page 1 is the listing's
// path, later pages <path>/page/[page]); pointing later pages at page 1 would
// tell search engines to ignore the posts listed only there. No rel=prev/next:
// the Metadata API has no field for it and major search engines ignore it.
export function buildArchiveMetadata(input: {
  title: string;
  description: string;
  path: string;
  site: SiteBrand;
  page?: number;
  // Interface language of the listing: the page-title format and og:locale
  // (interfaceOpenGraphLocales). Post pages use the post's own language.
  pageTitle: PageTitleFormatter;
  locale: string;
  // The archive's own feed (src/features/seo/archive-feed.ts), linked from
  // every page of the archive.
  feed?: Pick<FeedChannel, "path" | "title">;
}): Metadata {
  const page = input.page ?? 1;
  const path = pagePath(input.path, page);
  const title = pageTitle(input.title, page, input.pageTitle);
  const social = socialImages(defaultSocialImage(input.site), {
    title,
    description: input.description,
  });

  return {
    title,
    description: input.description,
    alternates: canonicalAlternates(path, input.site.siteName, input.feed),
    openGraph: {
      type: "website",
      url: path,
      siteName: input.site.siteName,
      locale: input.locale,
      title,
      description: input.description,
      ...social.openGraph,
    },
    twitter: social.twitter,
  };
}
